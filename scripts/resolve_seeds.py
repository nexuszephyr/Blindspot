"""Resolve every persona seed, interest tag and audience to a Qloo id and lock it (#15).

    python scripts/resolve_seeds.py [--dry-run] [--only seeds|tags|audiences] [--max-calls 150]

Reads config/ with `load_catalog()` and writes:
- config/resolved_ids.lock.json (committed): our query text, kind, domain, the chosen Qloo id,
  confidence, the ambiguous flag and a reason. No Qloo names or other response fields (D5).
  Deterministic, so an unchanged config re-runs to a byte-identical file with 0 live calls.
- data/resolved_ids.detail.json (gitignored): the top 3 candidates per item with their Qloo names,
  for human review.
- the generated block in docs/seed_review.md: counts, and every ambiguous or unresolved item by
  our query text.

The rules that pick an id live in src/blindspot/idlock.py. Every lookup goes through QlooClient
(cache, budgets, breaker, call log) with purpose `recon`. `--max-calls` stops before a lookup that
would be live once the cap is reached (cached lookups pass) and keeps what's done. `--dry-run` uses a
replay-mode client: it lists each lookup as cached or LIVE, never reaches the network and writes
nothing. Summaries print counts only.
"""

