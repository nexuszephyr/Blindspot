"""Phase 2 answer-key experiments E12-E15 (#13).

    python scripts/experiments_p2.py [--only E12,E13,E14,E15] [--dry-run] [--report] [--max-calls 170]

- E12 depth: the standard query per domain at take 10/20/30/50, the between-city overlap per rank
  band, and how persona-specific the tail is.
- E13 dining shape: location filter + restaurant tag + entity / tag / audience signals and each
  pair: scores, latency, repeat stability (cache bypassed) and persona specificity.
- E14 candidate scoring: score_candidates() over the E12 take=50 pool, per signal and size.
- E15 persona sensitivity: 4 personas per domain and city; pairwise top-10 Jaccard.

Cities, domains and personas come from config/ (cities.yaml, domains.yaml, experiments_p2.yaml).
Every call goes through QlooClient with purpose `recon`, one run id per experiment, so a re-run is
cache hits. The two E13 stability runs can't be cache hits (the repeat bypasses the cache and
overwrites the entry), so they are reused from the recording, as are cells that failed (pass
--retry-failed to try those again).

Recordings with ids stay in data/experiments_p2/ (gitignored): <exp>.json per experiment and
summary.json with aggregates only. `--report` rewrites the generated block in
docs/qloo_api_reality.md from summary.json without creating a client. `--dry-run` uses a
replay-mode client and lists the planned live calls per experiment; it never reaches the network.
The dry run counts cells; client retries on timeouts add live attempts (each retry is budgeted),
and --max-calls counts attempts, so the cap holds.
"""

