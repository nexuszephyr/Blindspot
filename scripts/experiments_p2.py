# Thresholds, stated in the generated doc.
GENERIC_TAIL = 0.3  # a rank band is generic when its between-city Jaccard exceeds this (top 10: <= 0.12)
STABLE_JACCARD = 0.9  # E13: repeat with the cache bypassed must keep this much of the top 10
