class Stop(Exception):
    """Budget cap reached or a dependency missing: stop cleanly and keep what was recorded."""


# --- pure helpers (unit-tested) -----------------------------------------------------------------


def jaccard(a: list[str], b: list[str]) -> float | None:
    sa, sb = set(a), set(b)
    return round(len(sa & sb) / len(sa | sb), 3) if sa and sb else None


def band_overlap(a: list[str], b: list[str], lo: int, hi: int) -> float | None:
    """Jaccard of ranks lo+1..hi of two ranked lists; None if either list doesn't reach the band."""
    return jaccard(a[lo:hi], b[lo:hi])


def pairwise(lists: dict[str, list[str]]) -> dict[str, Any]:
    """All pairwise top-10 Jaccards between non-empty lists, with mean and max."""
    vals = [jaccard(x[:10], y[:10]) for x, y in itertools.combinations([v for v in lists.values() if v], 2)]
    vals = [v for v in vals if v is not None]
    return {
        "pairs": vals,
        "mean": round(statistics.mean(vals), 3) if vals else None,
        "max": max(vals) if vals else None,
    }


def stability(first: list[str], repeat: list[str]) -> dict[str, Any]:
    return {
        "jaccard": jaccard(first, repeat),
        "rank_shift": rank_shift(first, repeat),
        "identical": first == repeat,
    }


def passes_e14(cell: dict[str, Any] | None) -> bool:
    """One candidate-scoring cell is useful: enough of N back, all from the pool, fast enough."""
    if not cell or cell["outcome"] != "ok":
        return False
    fast = cell["latency_ms"] is None or cell["latency_ms"] <= MAX_LATENCY_S * 1000
    return cell["count"] / cell["n"] >= USEFUL_RETURN and cell["all_in_pool"] and fast


def useful_max(cells: list[dict[str, Any]]) -> int | None:
    """Largest N that passes (E14 rule); None if no size does."""
    ok = [c["n"] for c in cells if passes_e14(c)]
    return max(ok) if ok else None


def latency_stats(ms: list[int | None]) -> dict[str, Any]:
    xs = [x for x in ms if x is not None]
    return {
        "p50_s": round(statistics.median(xs) / 1000, 2) if xs else None,
        "max_s": round(max(xs) / 1000, 2) if xs else None,
    }


def call_by_cities(oks: list[bool]) -> str:
    return "viable" if all(oks) else "marginal" if any(oks) else "not viable"


# --- runner -------------------------------------------------------------------------------------


class Runner:
    def __init__(self, client: QlooClient, *, max_calls: int, dry: bool, retry_failed: bool):
        self.client, self.max_calls, self.dry, self.retry_failed = client, max_calls, dry, retry_failed
        self.start = live_used(client)
        self.cities = self._cities()
        self.domains = load_domains(CONFIG)
        self.personas = yaml.safe_load((CONFIG / "experiments_p2.yaml").read_text(encoding="utf-8"))[
            "personas"
        ]
        self.plan: Counter[str] = Counter()
        self.raw: dict[str, dict[str, Any]] = {e: {} for e in EXPS}
        self.prev = {e: _load(OUT / f"{e}.json").get("cells", {}) for e in EXPS}
        self.summary = _load(OUT / "summary.json")
        self.ctxs = {e: ctx(f"experiments_p2_{e}", purpose="recon") for e in (*EXPS, "lookups")}
        self.resolved: dict[tuple, list[str]] = {}

    @staticmethod
    def _cities():
        all_cities = load_cities(CONFIG)
        return [next(c for c in all_cities if c.tier == t) for t in (1, 2)]

    def used(self) -> int:
        return live_used(self.client) - self.start

    def guard(self, path: str = "", params: dict | None = None) -> None:
        """Hard stop before a call that would be live once --max-calls is reached; cached calls pass."""
        if self.dry or self.used() < self.max_calls:
            return
        if path and self.client.cache.get(cache_key("GET", path, normalize_params(params))) is not None:
            return
        raise Stop(f"stopped at {self.used()} live calls (--max-calls {self.max_calls})")

    def std(self, d, city, take: int) -> dict[str, Any]:
        return {"filter.type": d.filter_type, **d.params, **d.location_params(city), "take": take}

    async def ids(self, persona: dict, domain_id: str, kind: str) -> list[str]:
        """Persona signal ids for one domain: audiences as configured, names resolved (cached)."""
        if kind == "audience":
            return list(persona["audiences"])
        key = (persona["id"], domain_id, kind)
        if key not in self.resolved:
            spec = persona["domains"][domain_id]
            if kind == "entity":
                param, names = SIGNAL_PARAM["entity"], [(s["name"], s["type"]) for s in spec["seeds"]]
            else:
                param, names = SIGNAL_PARAM["tag"], [spec["tag_query"]]
            for n in names:  # the same lookups resolve_ids makes
                name, etype = n if isinstance(n, tuple) else (n, None)
                if kind == "entity":
                    self.guard("/search", {"query": name, "types": [etype] if etype else None, "take": 1})
                else:
                    self.guard("/v2/tags", {"filter.query": name, "take": 1})
            before = live_used(self.client)
            got, missing = await self.client.resolve_ids(param, names, self.ctxs["lookups"])
            self.plan["lookups"] += len(missing) if self.dry else live_used(self.client) - before
            if missing and self.dry:
                got += [PLACEHOLDER[kind].format(i) for i in range(len(missing))]
            self.resolved[key] = got if not missing or self.dry else []
        return self.resolved[key]

    async def signals(self, persona: dict, d, combo: str) -> dict[str, list[str]] | None:
        out = {}
        for kind in combo.split("+"):
            got = await self.ids(persona, d.id, kind)
            if not got:
                return None  # resolution failed: the cell is skipped and reported, never sent as text
            out[SIGNAL_PARAM[kind]] = got
        return out

    async def q(self, exp: str, key: str, params: dict, *, how: str = "insights", pinned: bool = False):
        """One recorded call. Reuses the recording for pinned cells and (unless --retry-failed) failures."""
        prev = self.prev[exp].get(key)
        if prev and (pinned or (prev["outcome"] != "ok" and not self.retry_failed)):
            self.raw[exp][key] = prev
            return prev
        self.guard(
            "" if how == "bypass" else "/v2/insights", InsightsQuery.model_validate(params).to_params()
        )
        c = self.ctxs[exp]
        if how == "bypass":
            r = await self.client.request(
                "/v2/insights", InsightsQuery.model_validate(params).to_params(), c, bypass_cache=True
            )
        elif how == "score":
            rest = {
                k: v for k, v in params.items() if k not in ("filter.type", "filter.results.entities", "take")
            }
            r = await self.client.score_candidates(
                params["filter.type"], params["filter.results.entities"], c, **rest
            )
        else:
            r = await self.client.insights(params, c)
        cell = {
            "params": params,
            "served_from": r.served_from,
            "outcome": r.outcome,
            "count": r.count,
            "ids": [e.entity_id for e in r.entities],
            "n_scored": sum(e.affinity is not None for e in r.entities),
            "latency_ms": round(r.latency_ms) if r.served_from == "live" and r.latency_ms else None,
            "reason": (r.reason or "")[:160],
        }
        if cell["latency_ms"] is None and prev:  # a cache hit keeps the latency measured when it was live
            cell["latency_ms"] = prev.get("latency_ms")
        if r.served_from not in ("cache", "snapshot"):
            self.plan[exp] += 1
        self.raw[exp][key] = cell
        if not self.dry:
            _save(OUT / f"{exp}.json", {"cells": self.raw[exp]})
        return cell

    # --- experiments ----------------------------------------------------------------------------

    async def e12(self) -> dict[str, Any]:
        a, (c0, c1) = self.personas[0], self.cities
        out: dict[str, Any] = {"domains": {}, "counts": []}
        exact = True
        for d in self.domains:
            sig = await self.signals(a, d, "audience")
            cells = {}
            for city in self.cities:
                for take in TAKES:
                    cells[(city.id, take)] = await self.q(
                        "E12", f"{d.id}/{city.id}/take{take}", self.std(d, city, take)
                    )
                cells[(city.id, "persona")] = await self.q(
                    "E12", f"{d.id}/{city.id}/persona_take50", {**self.std(d, city, 50), **sig}
                )
            ids = {k: v["ids"] for k, v in cells.items()}
            out["counts"] += [cells[(c.id, t)]["count"] for c in self.cities for t in TAKES]
            exact &= all(cells[(c.id, t)]["count"] == t for c in self.cities for t in TAKES)
            bands = {
                f"{lo + 1}-{hi}": band_overlap(ids[(c0.id, 50)], ids[(c1.id, 50)], lo, hi) for lo, hi in BANDS
            }
            persona_tail = {
                c.id: band_overlap(ids[(c.id, 50)], ids[(c.id, "persona")], 20, 50) for c in self.cities
            }
            full = {t: all(cells[(c.id, t)]["count"] >= t for c in self.cities) for t in TAKES}
            specific = {b: v is not None and v <= GENERIC_TAIL for b, v in bands.items()}
            depth = 20 if full[20] and specific["11-20"] else 10
            pool = 50 if full[50] and specific["21-50"] else depth
            out["domains"][d.id] = {
                "counts": {c.id: {str(t): cells[(c.id, t)]["count"] for t in TAKES} for c in self.cities},
                "scored": all(
                    cells[(c.id, t)]["n_scored"] == cells[(c.id, t)]["count"] > 0
                    for c in self.cities
                    for t in TAKES
                ),
                "top10_equal": {
                    str(t): all(ids[(c.id, t)][:10] == ids[(c.id, 10)] for c in self.cities)
                    for t in TAKES[1:]
                },
                "city_band_jaccard": bands,
                "persona_tail_jaccard": persona_tail,
                "outcomes_ok": all(v["outcome"] == "ok" for v in cells.values()),
                "depth": depth,
                "membership_pool": pool,
            }
        counts = out["counts"]
        out["count_distribution"] = {
            "min": min(counts),
            "median": statistics.median(counts),
            "max": max(counts),
            "n": len(counts),
        }
        out["degenerate"] = exact  # every cell returned exactly `take`
        return out

    async def e13(self) -> dict[str, Any]:
        d = next(x for x in self.domains if x.filter_type == "urn:entity:place")
        a, b = self.personas[0], self.personas[1]
        shapes: dict[str, Any] = {}
        for shape in SHAPES:
            sa, sb = await self.signals(a, d, shape), await self.signals(b, d, shape)
            per_city, lat, ok = {}, [], True
            for city in self.cities:
                base = self.std(d, city, 10)
                if sa is None or sb is None:
                    ok = False
                    continue
                key = f"{city.id}/{shape}"
                r1 = await self.q("E13", f"{key}/A/run1", {**base, **sa}, pinned=True)
                r2 = await self.q("E13", f"{key}/A/run2", {**base, **sa}, how="bypass", pinned=True)
                rb = await self.q("E13", f"{key}/B", {**base, **sb})
                ok &= all(x["outcome"] == "ok" for x in (r1, r2, rb))
                lat += [r1["latency_ms"], r2["latency_ms"], rb["latency_ms"]]
                per_city[city.id] = {
                    "count": r1["count"],
                    "scored": r1["n_scored"] == r1["count"] > 0 and rb["n_scored"] == rb["count"] > 0,
                    "stability": stability(r1["ids"], r2["ids"]),
                    "persona_jaccard": jaccard(r1["ids"], rb["ids"]),
                    "first_run_from_cache": r1["served_from"] == "cache",
                    "outcomes": [r1["outcome"], r2["outcome"], rb["outcome"]],
                }
            shapes[shape] = {
                "cities": per_city,
                "latency": latency_stats(lat),
                "all_ok": ok and len(per_city) == 2,
            }
        return {"shapes": shapes, **pick_shape(shapes)}

    async def e14(self) -> dict[str, Any]:
        a = self.personas[0]
        pools = self._pools()
        grid: dict[str, Any] = {}
        for d in self.domains:
            cells = []
            for kind, n, ci in E14_CELLS:
                city = self.cities[ci]
                sig = await self.signals(a, d, kind)
                cands = pools[(d.id, city.id)][:n]
                if sig is None or len(cands) < n:
                    cells.append({"signal": kind, "n": n, "city": city.id, "outcome": "skipped", "count": 0})
                    continue
                params = {**self.std(d, city, n), "filter.results.entities": cands, **sig}
                r = await self.q("E14", f"{d.id}/{city.id}/{kind}/{n}", params, how="score")
                cells.append(
                    {
                        "signal": kind,
                        "n": n,
                        "city": city.id,
                        "outcome": r["outcome"],
                        "count": r["count"],
                        "scored_share": round(r["n_scored"] / r["count"], 2) if r["count"] else 0.0,
                        "latency_ms": r["latency_ms"],
                        "all_in_pool": set(r["ids"]) <= set(cands),
                    }
                )
            grid[d.id] = {"cells": cells, **e14_verdicts(cells)}
        fallback = all(len(p) >= 50 for p in pools.values())
        return {"grid": grid, "fallback_top50_computable": fallback}

    def _pools(self) -> dict[tuple[str, str], list[str]]:
        cells = self.raw["E12"] or self.prev["E12"]
        pools = {}
        for d in self.domains:
            for city in self.cities:
                cell = cells.get(f"{d.id}/{city.id}/take50")
                if cell is None and not self.dry:
                    raise Stop("E14 needs the E12 take=50 pool: run E12 first")
                if cell is None or (
                    self.dry and not cell["ids"]
                ):  # dry run only: placeholders, never sent live
                    pools[(d.id, city.id)] = [PLACEHOLDER["entity"].format(i) for i in range(50)]
                else:
                    pools[(d.id, city.id)] = cell["ids"]
        return pools

    async def e15(self) -> dict[str, Any]:
        pick = (self.summary.get("E13") or {}).get("pick")
        if pick is None:
            if not self.dry:
                raise Stop("E15 needs an E13 dining pick: run E13 first")
            pick = "audience"  # dry run before E13 exists: a placeholder for counting only
        out: dict[str, Any] = {"dining_shape": pick, "domains": {}}
        for d in self.domains:
            combo = pick if d.filter_type == "urn:entity:place" else "audience"
            per_city = {}
            for city in self.cities:
                lists = {}
                for p in self.personas:
                    sig = await self.signals(p, d, combo)
                    if sig is None:
                        continue
                    r = await self.q("E15", f"{d.id}/{city.id}/{p['id']}", {**self.std(d, city, 10), **sig})
                    if r["outcome"] == "ok":
                        lists[p["id"]] = r["ids"]
                per_city[city.id] = {**pairwise(lists), "personas_ok": len(lists)}
            means_ok = [
                v["mean"] is not None and v["mean"] < PERSONA_VIABLE and v["personas_ok"] == 4
                for v in per_city.values()
            ]
            out["domains"][d.id] = {"signal": combo, "cities": per_city, "call": call_by_cities(means_ok)}
        return out


def pick_shape(shapes: dict[str, Any]) -> dict[str, Any]:
    """E13 rule: scores everywhere, stable on repeat, fast, then the most persona-specific (lowest
    mean Jaccard between personas); ties go to the shape with fewer signals."""
    eligible = []
    for name, s in shapes.items():
        cs = list(s["cities"].values())
        if not s["all_ok"] or not all(c["scored"] for c in cs):
            continue
        if not all((c["stability"]["jaccard"] or 0) >= STABLE_JACCARD for c in cs):
            continue
        lat = s["latency"]
        if lat["p50_s"] is not None and (lat["p50_s"] > MAX_LATENCY_S or lat["max_s"] >= DEADLINE_S):
            continue
        specificity = statistics.mean(c["persona_jaccard"] or 0 for c in cs)
        eligible.append((specificity, name.count("+"), name))
    if not eligible:
        return {"pick": None, "eligible": []}
    eligible.sort()
    return {"pick": eligible[0][2], "eligible": [n for _, _, n in eligible]}


def e14_verdicts(cells: list[dict[str, Any]]) -> dict[str, Any]:
    """works: the 25-candidate cell passes in both cities; partial: in one city, or at least half of
    N comes back from the pool in both; fails: otherwise. Useful max from the entity sizes, city 1."""
    verdicts = {}
    for kind in SIGNAL_PARAM:
        at25 = [c for c in cells if c["signal"] == kind and c["n"] == 25]
        passed = [passes_e14(c) if "all_in_pool" in c else False for c in at25]
        half = all(c.get("all_in_pool") and c["count"] / c["n"] >= 0.5 for c in at25) if at25 else False
        verdicts[kind] = "works" if passed and all(passed) else "partial" if any(passed) or half else "fails"
    first_city = cells[0]["city"] if cells else None
    sizes = [c for c in cells if c["signal"] == "entity" and c["city"] == first_city and "all_in_pool" in c]
    return {"verdicts": verdicts, "useful_max_entity": useful_max(sizes)}


# --- recordings and report ----------------------------------------------------------------------


def _load(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}


def _save(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1, default=str), encoding="utf-8")


def _f(v: Any) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    return str(v)


def _failures(shape: dict[str, Any]) -> str:
    cities = shape["cities"].values()
    bad = [sum(o != "ok" for o in c["outcomes"]) for c in cities]
    total = sum(len(c["outcomes"]) for c in cities)
    return f"{sum(bad)} of {total} requests, {sum(b > 0 for b in bad)} of {len(bad)} cities"


def phase1_rows(s: dict[str, Any]) -> list[tuple[str, str, str]]:
    """Like-for-like comparisons with what Phase 1 reported: (check, Phase 1, now)."""
    rows = []
    if e12 := s.get("E12"):
        doms = e12["domains"].values()
        rows.append(
            ("Top 10 unchanged at take 20", "yes (E11)", _f(all(v["top10_equal"]["20"] for v in doms)))
        )
        top = max((v["city_band_jaccard"]["1-10"] or 0) for v in doms)
        rows.append(("Max between-city top-10 Jaccard", "≤ 0.12 (coverage swap)", _f(top)))
    if e13 := s.get("E13"):
        shapes, pick = e13["shapes"], e13.get("pick")
        if pick:
            p50 = shapes[pick]["latency"]["p50_s"]
            rows.append(
                (f"Dining p50, picked shape ({pick})", "about 2.4 s (coverage, age signal)", f"{_f(p50)} s")
            )
        lat = [v["latency"]["p50_s"] for v in shapes.values() if v["latency"]["p50_s"] is not None]
        rows.append(
            (
                f"Dining p50, all {len(shapes)} shapes (median)",
                "-",
                f"{_f(round(statistics.median(lat), 2)) if lat else '-'} s",
            )
        )
        if "audience" in shapes:
            rows.append(
                (
                    "Dining audience-only failures",
                    "1 of 2 cities timed out (E11)",
                    _failures(shapes["audience"]),
                )
            )
        if "tag+audience" in shapes:
            rows.append(("Dining tag+audience failures", "-", _failures(shapes["tag+audience"])))
    return rows


def _claims(rows: list[tuple[str, bool | str]]) -> list[str]:
    """Claim table: a bool is VERIFIED / FAILED (the claim was tested and is false); a str is kept."""
    out = ["| Claim | Label |", "|---|---|"]
    for claim, ok in rows:
        out.append(f"| {claim} | {ok if isinstance(ok, str) else 'VERIFIED' if ok else 'FAILED'} |")
    return [*out, ""]


def _names(d: dict[str, Any], want) -> str:
    return ", ".join(k for k, v in d.items() if want(v)) or "none"


def render(s: dict[str, Any]) -> str:
    """Markdown for the reality doc, from aggregates only (no names, ids or scores)."""
    date, cities = s.get("date", "-"), ", ".join(s.get("cities", []))
    out = [BEGIN, ""]
    out += [
        f"Run {date} by `scripts/experiments_p2.py` (purpose `recon`) in {cities} (first tier-1 and tier-2 city "
        "in `config/cities.yaml`), with the draft personas in `config/experiments_p2.yaml`. Recordings with ids "
        "are in `data/experiments_p2/`; these tables are regenerated from `summary.json` with `--report`.",
        "",
        f"Thresholds: a rank band is *generic* when its between-city Jaccard is above {GENERIC_TAIL}; a shape is "
        f"*stable* at a repeat Jaccard ≥ {STABLE_JACCARD}; a dining shape is *fast* at p50 ≤ {MAX_LATENCY_S} s with "
        f"its slowest call under the {DEADLINE_S} s request deadline; candidate scoring is "
        f"*useful* when ≥ {USEFUL_RETURN} of N come back, all from the pool, within {MAX_LATENCY_S} s; the "
        f"audience probe is *viable* when "
        f"the mean pairwise persona Jaccard is < {PERSONA_VIABLE}.",
        "",
    ]
    if e := s.get("E12"):
        dist = e["count_distribution"]
        out += [
            f"## E12. Answer-key depth ({date})",
            "",
            "| Domain | Counts at take 10/20/30/50 (per city) | Scores | Top 10 unchanged at take 20/30/50 | City Jaccard 1-10 / 11-20 / 21-50 | Persona tail Jaccard (21-50 vs standard) | Depth | Membership pool |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for dom, v in e["domains"].items():
            counts = "; ".join(
                f"{c}: {'/'.join(_f(n) for n in v['counts'][c].values())}" for c in v["counts"]
            )
            top10 = "/".join(_f(v["top10_equal"][str(t)]) for t in TAKES[1:])
            bands = " / ".join(_f(x) for x in v["city_band_jaccard"].values())
            tail = ", ".join(_f(x) for x in v["persona_tail_jaccard"].values())
            out.append(
                f"| {dom} | {counts} | {_f(v['scored'])} | {top10} | {bands} | {tail} | **{v['depth']}** | {v['membership_pool']} |"
            )
        out += [
            "",
            f"Counts over {dist['n']} cells: min {dist['min']}, median {dist['median']}, max {dist['max']}. "
            + (
                "Every cell returned exactly `take` results, so the distribution can't separate rich from thin cells: "
                "the thresholds below are **provisional** for #24."
                if e["degenerate"]
                else ""
            ),
            "",
            "Depth rule: 20 when both cities fill take=20 and ranks 11-20 stay city-specific, else 10. Membership "
            "pool: 50 when take=50 fills and ranks 21-50 stay city-specific (E14 fallback).",
            "",
        ]
        doms = e["domains"]
        out += _claims(
            [
                ("take 20, 30 and 50 return full lists in every domain and city", e["degenerate"]),
                (
                    "The top 10 stays the same as take grows to 20, 30 and 50",
                    all(all(v["top10_equal"].values()) for v in doms.values()),
                ),
                (
                    f"Ranks 11-20 and 21-50 stay city-specific (between-city Jaccard ≤ {GENERIC_TAIL})",
                    all(
                        (x or 0) <= GENERIC_TAIL
                        for v in doms.values()
                        for x in v["city_band_jaccard"].values()
                    ),
                ),
                (
                    f"A persona audience changes ranks 21-50 (Jaccard vs the standard query ≤ {GENERIC_TAIL})",
                    all(
                        (x or 0) <= GENERIC_TAIL
                        for v in doms.values()
                        for x in v["persona_tail_jaccard"].values()
                    ),
                ),
                (
                    f"The location-only standard query carries scores for: {_names(doms, lambda v: v['scored'])}; "
                    f"not for: {_names(doms, lambda v: not v['scored'])} (as E11)",
                    "VERIFIED",
                ),
            ]
        )
    if e := s.get("E13"):
        out += [
            f"## E13. Dining query shape ({date})",
            "",
            "Base: `filter.location.query` + the restaurant `filter.tags` (`signal.location.query` is DISCOURAGED for "
            "places). Persona A runs twice (the second with the cache bypassed); persona B runs once.",
            "",
            "| Shape | All ok | Scores | Count | Repeat Jaccard / rank shift (per city) | Persona A vs B Jaccard | Latency p50 / max |",
            "|---|---|---|---|---|---|---|",
        ]
        for name, v in e["shapes"].items():
            cs = v["cities"].values()
            rep = ", ".join(
                f"{_f(c['stability']['jaccard'])} / {_f(c['stability']['rank_shift'])}" for c in cs
            )
            out.append(
                f"| {name} | {_f(v['all_ok'])} | {_f(all(c['scored'] for c in cs))} | {', '.join(_f(c['count']) for c in cs)} "
                f"| {rep} | {', '.join(_f(c['persona_jaccard']) for c in cs)} | {_f(v['latency']['p50_s'])} s / {_f(v['latency']['max_s'])} s |"
            )
        drift = sorted(
            f"{k} ({c})"
            for k, v in e["shapes"].items()
            for c, x in v["cities"].items()
            if x["first_run_from_cache"]
        )
        out += [
            "",
            f"**Pick: `{e['pick']}`** (eligible: {', '.join(e['eligible']) or 'none'}). Rule: all cells ok, scores in "
            f"every cell, stable in both cities, p50 ≤ {MAX_LATENCY_S} s and the slowest call under {DEADLINE_S} s, then "
            "the lowest persona Jaccard; ties go to fewer signals.",
            "",
        ]
        shapes = e["shapes"]
        answered = [c for v in shapes.values() for c in v["cities"].values() if set(c["outcomes"]) == {"ok"}]
        strict = [n for n in e["eligible"] if (shapes[n]["latency"]["max_s"] or 0) <= MAX_LATENCY_S]
        failed = sorted(
            f"{n} ({c})"
            for n, v in shapes.items()
            for c, x in v["cities"].items()
            if set(x["outcomes"]) != {"ok"}
        )
        out += _claims(
            [
                (
                    f"Every shape that answered is stable on repeat (Jaccard ≥ {STABLE_JACCARD})",
                    all((c["stability"]["jaccard"] or 0) >= STABLE_JACCARD for c in answered),
                ),
                (
                    "A taste signal gives dining scores in every shape that answered",
                    all(c["scored"] for c in answered),
                ),
                (
                    f"Shapes whose slowest call stayed under {DEADLINE_S} s: "
                    f"{_names(shapes, lambda v: v['all_ok'] and (v['latency']['max_s'] or 0) < DEADLINE_S)}",
                    "VERIFIED",
                ),
                (
                    f"Shapes with failed calls (timeouts after retries): {', '.join(failed) or 'none'}",
                    "VERIFIED",
                ),
                (
                    f"Under a stricter rule (slowest call ≤ {MAX_LATENCY_S} s) the eligible shapes would be: "
                    f"{', '.join(strict) or 'none'}",
                    "VERIFIED",
                ),
            ]
        )
        if drift:
            out += [
                f"First runs served from the Phase 1 cache ({', '.join(drift)}) compare a result from about five days "
                "earlier with today's, so their repeat figure measures drift, not immediate repeatability.",
                "",
            ]
    if e := s.get("E14"):
        out += [
            f"## E14. Candidate scoring ({date})",
            "",
            "`score_candidates()` (`filter.results.entities`) with the location and one persona signal, over the "
            "E12 take=50 standard list. Cells: returned/N, share scored, latency; a cross means some returned ids "
            "were outside the pool.",
            "",
            "| Domain | "
            + " | ".join(f"{k} {n} ({c})" for k, n, c in _e14_cols(e))
            + " | entity / tag / audience | Useful max (entity) |",
            "|---|" + "---|" * (len(_e14_cols(e)) + 2),
        ]
        for dom, v in e["grid"].items():
            cells = []
            for c in v["cells"]:
                if c["outcome"] != "ok":
                    cells.append(c["outcome"])
                    continue
                lat = "cache" if c["latency_ms"] is None else f"{c['latency_ms'] / 1000:.1f} s"
                cells.append(
                    f"{c['count']}/{c['n']}, {c['scored_share']}, {lat}{'' if c['all_in_pool'] else ' ✗'}"
                )
            verdicts = " / ".join(v["verdicts"][k] for k in SIGNAL_PARAM)
            out.append(f"| {dom} | {' | '.join(cells)} | {verdicts} | {_f(v['useful_max_entity'])} |")
        out += [
            "",
            "Verdict: *works* when the 25-candidate cell passes in both cities, *partial* when it passes in one or "
            "at least half of N comes back from the pool in both, *fails* otherwise. Location alone is not re-run: "
            "it returned 1 of N (E7). Fallback for anything short of *works*: rank membership in the local top-50 "
            f"from E12 (computable from the recordings: {_f(e['fallback_top50_computable'])}).",
            "",
        ]
        grid = e["grid"]
        cells = [c for v in grid.values() for c in v["cells"] if c["outcome"] == "ok"]
        rows = []
        for kind in SIGNAL_PARAM:
            by = {d: v["verdicts"][kind] for d, v in grid.items()}
            rows.append(
                (
                    f"{kind} signal: works for {_names(by, lambda x: x == 'works')}; partial for "
                    f"{_names(by, lambda x: x == 'partial')}; fails for {_names(by, lambda x: x == 'fails')}",
                    "VERIFIED",
                )
            )
        rows += [
            ("Every returned id was in the candidate pool", all(c["all_in_pool"] for c in cells)),
            ("Every returned candidate carries a score", all(c["scored_share"] == 1.0 for c in cells)),
            (
                "Useful maximum with an entity signal: "
                + ", ".join(f"{d} {_f(v['useful_max_entity'])}" for d, v in grid.items()),
                "VERIFIED",
            ),
            ("Location alone ranks 1 of N", "VERIFIED (Phase 1 E7, not re-run)"),
        ]
        out += _claims(rows)
    if e := s.get("E15"):
        out += [
            f"## E15. Persona sensitivity ({date})",
            "",
            f"4 personas per domain and city, top 10 each. Signal: the persona's audience; dining uses the E13 pick "
            f"(`{e['dining_shape']}`). Six pairwise Jaccards per cell.",
            "",
            "| Domain | Signal | "
            + " | ".join(f"{c} mean / max" for c in s.get("cities", []))
            + " | Audience probe |",
            "|---|---|" + "---|" * (len(s.get("cities", [])) + 1),
        ]
        for dom, v in e["domains"].items():
            cs = " | ".join(f"{_f(c['mean'])} / {_f(c['max'])}" for c in v["cities"].values())
            out.append(f"| {dom} | {v['signal']} | {cs} | **{v['call']}** |")
        out += [
            "",
            f"Call: *viable* when the mean is below {PERSONA_VIABLE} in both cities (with all 4 personas returned), "
            "*marginal* in one, *not viable* in neither.",
            "",
        ]
        doms = e["domains"]
        out += _claims(
            [
                (f"Audience probe viable for: {_names(doms, lambda v: v['call'] == 'viable')}", "VERIFIED"),
                (f"Marginal for: {_names(doms, lambda v: v['call'] == 'marginal')}", "VERIFIED"),
                (f"Not viable for: {_names(doms, lambda v: v['call'] == 'not viable')}", "VERIFIED"),
            ]
        )
    if rows := phase1_rows(s):
        out += ["### Phase 1 cross-checks", "", "| Check | Phase 1 | Now |", "|---|---|---|"]
        out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
        out.append("")
    out.append(END)
    return "\n".join(out)


def _e14_cols(e: dict[str, Any]) -> list[tuple[str, int, str]]:
    first = next(iter(e["grid"].values()))["cells"]
    return [(c["signal"], c["n"], c["city"]) for c in first]


def write_report(summary: dict[str, Any]) -> None:
    text = DOC.read_text(encoding="utf-8")
    block = render(summary)
    if BEGIN in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END) :]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(text, encoding="utf-8", newline="\n")


# --- main ---------------------------------------------------------------------------------------


async def run(a: argparse.Namespace, client: QlooClient) -> dict[str, Any]:
    r = Runner(client, max_calls=a.max_calls, dry=a.dry_run, retry_failed=a.retry_failed)
    only = [x.strip().upper() for x in a.only.split(",")] if a.only else list(EXPS)
    stopped = None
    try:
        for exp in EXPS:
            if exp in only:
                r.summary[exp] = await getattr(r, exp.lower())()
    except Stop as exc:
        stopped = str(exc)
    r.summary.pop("phase1_checks", None)  # computed at render time
    r.summary["cities"] = [c.id for c in r.cities]
    r.summary["date"] = time.strftime("%Y-%m-%d")
    r.summary["tags"] = {f"{p}/{d}": v for (p, d, k), v in r.resolved.items() if k == "tag"}
    if not a.dry_run:
        _save(OUT / "summary.json", r.summary)
    return {"plan": dict(r.plan), "live_calls": r.used(), "stopped": stopped, "summary": r.summary}


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", help="comma-separated subset of E12,E13,E14,E15")
    p.add_argument("--dry-run", action="store_true", help="list planned live calls; make none")
    p.add_argument(
        "--report", action="store_true", help="regenerate the doc block from summary.json; no client"
    )
    p.add_argument("--max-calls", type=int, default=170, help="hard stop on live calls for this invocation")
    p.add_argument("--retry-failed", action="store_true", help="re-send cells that failed last time")
    return p


def main(argv: list[str] | None = None) -> int:
    a = parser().parse_args(argv)
    if a.report:
        summary = _load(OUT / "summary.json")
        if not summary:
            sys.exit(f"no recordings: {OUT / 'summary.json'} is missing")
        write_report(summary)
        print(f"report written to {DOC} (0 calls)")
        return 0
    client = QlooClient(Settings(qloo_mode="replay")) if a.dry_run else make_client("live")
    try:
        out = asyncio.run(run(a, client))
    finally:
        client.db.close()
    if a.dry_run:
        for k, v in sorted(out["plan"].items()):
            print(f"{k}: {v} live")
        print(f"dry run total: {sum(out['plan'].values())} live calls (cached cells not counted)")
        return 0
    write_report(out["summary"])
    print(f"live calls by experiment: {out['plan']}; total {out['live_calls']}")
    if out["stopped"]:
        print(out["stopped"])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
