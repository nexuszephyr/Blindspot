CONFIG = ROOT / "config"
DETAIL = DATA / "resolved_ids.detail.json"
REVIEW = ROOT / "docs" / "seed_review.md"
BEGIN = "<!-- BEGIN resolve_seeds: generated by scripts/resolve_seeds.py; don't edit by hand -->"
END = "<!-- END resolve_seeds -->"
KINDS = {"seeds": "seed", "tags": "tag", "audiences": "audience"}
SEARCH_TAKE, TAG_TAKE, AUDIENCE_TAKE = 5, 10, 50


class Stop(Exception):
    """The --max-calls cap was reached before a live lookup."""


class Collapse(Exception):
    """Two personas resolve to the same audience set (their answer keys would be identical)."""


@dataclass
class Work:
    kind: str
    domain: str
    query: str
    search_type: str | None = None
    personas: list[str] = field(default_factory=list)

    @property
    def key(self) -> str:
        return lock_key(self.kind, self.domain, self.query)


def work_list(cat: Catalog) -> dict[str, Work]:
    """One item per distinct (kind, domain, query) in the personas, with who uses it."""
    out: dict[str, Work] = {}

    def add(w: Work, persona: str) -> None:
        out.setdefault(w.key, w).personas.append(persona)

    for p in cat.personas:
        for d, seeds in p.seeds.items():
            for s in seeds:
                add(Work("seed", d, s.name, s.type), p.id)
        for d, tags in p.interest_tags.items():
            for t in tags:
                add(Work("tag", d, t), p.id)
        for a in p.audiences:
            add(Work("audience", "*", f"{a.type}:{a.name}" if isinstance(a, AudienceName) else a), p.id)
    return dict(sorted(out.items()))


def _candidates(kind: str, hits: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Top 3 hits for the detail file (gitignored): this is where Qloo names may go."""
    out = []
    for h in hits[:3]:
        typ = tag_family(str(h.get("id", ""))) if kind == "tag" else h.get("types") or h.get("type")
        ident = h.get("id") if kind != "seed" else h.get("entity_id")
        out.append({"name": h.get("name"), "type": typ, "popularity": h.get("popularity"), "id": ident})
    return out


class Resolver:
    def __init__(self, client: QlooClient, *, max_calls: int, dry: bool, previous: IdLock | None = None):
        self.client, self.max_calls, self.dry = client, max_calls, dry
        self.previous = previous or IdLock()
        self.failures = 0
        self.start = live_used(client)
        self.c = ctx("resolve_seeds", purpose="recon")
        self.plan: Counter[str] = Counter()
        self.items: dict[str, LockItem] = {}
        self.detail: dict[str, Any] = {}
        self.notes: dict[str, Any] = {}

    def used(self) -> int:
        return live_used(self.client) - self.start

    def guard(self, path: str, params: dict[str, Any]) -> None:
        """Hard stop before a lookup that would be live once --max-calls is reached."""
        if self.dry or self.used() < self.max_calls:
            return
        if self.client.cache.get(cache_key("GET", path, normalize_params(params))) is None:
            raise Stop(f"stopped at {self.used()} live calls (--max-calls {self.max_calls})")

    async def call(self, kind: str, path: str, params: dict[str, Any], fn):
        self.guard(path, params)
        before = live_used(self.client)
        r = await fn()
        if self.dry:
            self.plan[kind] += r.served_from not in ("cache", "snapshot")
        else:
            self.plan[kind] += live_used(self.client) - before
        return r

    def record(self, w: Work, d: Decision, hits: list[dict[str, Any]] | None) -> None:
        self.items[w.key] = LockItem(
            kind=w.kind, domain=w.domain, query=w.query, search_type=w.search_type, id=d.id,
            status=d.status, ambiguous=d.ambiguous, confidence=d.confidence, reason=d.reason,
        )  # fmt: skip
        self.detail[w.key] = {
            "query": w.query,
            "personas": w.personas,
            "candidates": _candidates(w.kind, hits or []),
            "chosen": d.id,
        }

    def failed(self, w: Work, reason: str) -> None:
        """A failed lookup (429, timeout, breaker...) never overwrites a locked id: the previous
        entry is kept when there is one; otherwise the item is unresolved with the reason."""
        self.failures += 1
        if w.key in self.previous.items:
            self.items[w.key] = self.previous.items[w.key]
            self.detail[w.key] = {"query": w.query, "personas": w.personas, "kept_previous": reason}
            return
        self.record(w, Decision(id=None, confidence=None, ambiguous=False, reason=reason), None)

    async def seeds(self, work: list[Work]) -> None:
        for w in work:
            params = {"query": w.query, "types": [w.search_type], "take": SEARCH_TAKE}
            r = await self.call(
                "seeds", "/search", params,
                lambda w=w: self.client.search_entities(w.query, self.c, types=[w.search_type], take=SEARCH_TAKE),
            )  # fmt: skip
            if not r.ok:
                self.failed(w, f"lookup failed: {r.outcome}")
                continue
            hits = [e.raw for e in r.entities]
            self.record(w, resolve_seed(w.query, w.search_type, hits), hits)

    async def tags(self, work: list[Work]) -> None:
        for w in work:
            params = {"filter.query": w.query, "take": TAG_TAKE}
            r = await self.call(
                "tags",
                "/v2/tags",
                params,
                lambda w=w: self.client.search_tags(self.c, query=w.query, take=TAG_TAKE),
            )
            if not r.ok:
                self.failed(w, f"lookup failed: {r.outcome}")
                continue
            hits = [e.raw for e in r.entities]
            self.record(w, resolve_tag(w.query, w.domain, hits), hits)

    async def audiences(self, work: list[Work]) -> None:
        def parent(w: Work) -> str:
            return w.query.split(":")[2] if w.query.startswith("urn:") else w.query.split(":", 1)[0]

        r = await self.call(
            "audiences",
            "/v2/audiences/types",
            {"take": 50},
            lambda: self.client.list_audience_types(self.c, take=50),
        )
        known = (
            {str(t.raw.get("type", "")).removeprefix("urn:audience:") for t in r.entities} if r.ok else set()
        )
        listings: dict[str, list[dict[str, Any]] | None] = {}
        self.truncated: dict[str, str] = {}
        truncated = self.truncated
        self.notes["pagination"] = {}
        for t in sorted({parent(w) for w in work}):
            params = {"filter.parents.types": [f"urn:audience:{t}"], "take": AUDIENCE_TAKE}
            lr = await self.call(
                "audiences", "/v2/audiences", params,
                lambda t=t: self.client.list_audiences(self.c, parent_types=[f"urn:audience:{t}"], take=AUDIENCE_TAKE),
            )  # fmt: skip
            listings[t] = [e.raw for e in lr.entities] if lr.ok else None
            self.notes["pagination"][t] = {"count": lr.count, "page2": None}
            if lr.ok and lr.count >= AUDIENCE_TAKE:
                await self.page_two(t, params, listings)
        self.notes["audience_types_listed"] = bool(known)
        for w in work:
            t, listing = parent(w), listings.get(parent(w))
            if known and t not in known:
                self.record(
                    w,
                    Decision(
                        id=None,
                        confidence=None,
                        ambiguous=False,
                        reason="parent type not in /v2/audiences/types",
                    ),
                    None,
                )
            elif listing is None:
                self.failed(w, "audience listing failed")
            else:
                if w.query.startswith("urn:"):
                    d = resolve_audience_urn(w.query, listing)
                else:
                    d = resolve_audience_name(w.query.split(":", 1)[1], listing)
                if d.status == "unresolved" and t in truncated and d.reason != "identity-based (AGENTS §13)":
                    d = Decision(id=None, confidence=None, ambiguous=False, reason=truncated[t])
                self.record(w, d, listing)

    async def page_two(self, t: str, params: dict[str, Any], listings: dict[str, Any]) -> None:
        """A type filled a page: ask for page 2 (lookup endpoints aren't param-guarded). New ids mean
        pagination works (VERIFIED) and are merged; the same ids mean `page` is ignored (FAILED), and
        names not found there may be on a page we can't reach."""
        p2 = {**params, "page": 2}
        r = await self.call(
            "audiences", "/v2/audiences", p2, lambda: self.client.request("/v2/audiences", p2, self.c)
        )
        first = listings[t]
        seen = set(listing_ids(first))
        new = [a for a in (e.raw for e in r.entities) if a.get("id") not in seen] if r.ok else []
        if not r.ok:
            verdict = f"UNVERIFIED (page 2 failed: {r.outcome})"
        elif new and listing_ids(new):
            verdict = "VERIFIED"
            listings[t] = first + new
        else:
            verdict = "FAILED (page 2 returned the same ids)"
        self.notes["pagination"][t]["page2"] = verdict
        if verdict != "VERIFIED" or len(new) >= AUDIENCE_TAKE:
            self.truncated[t] = f"listing may be truncated ({len(listings[t])} of take {AUDIENCE_TAKE})"

    def check_distinct(self, cat: Catalog) -> None:
        """Re-run D38's check with the resolved URNs: two personas must not share an audience set."""
        resolved = {}
        for p in cat.personas:
            for a in p.audiences:
                if isinstance(a, AudienceName):
                    item = self.items.get(lock_key("audience", "*", f"{a.type}:{a.name}"))
                    if item and item.id:
                        resolved[audience_key(a)] = item.id
        try:
            check_distinct_audiences(cat.personas, resolved, where="resolved audiences")
        except ConfigError as exc:
            raise Collapse(str(exc)) from None


def merge(old: IdLock, new: dict[str, LockItem], work: dict[str, Work], done_kinds: set[str]) -> IdLock:
    """Update the lock with this run's items. Items no longer in config are dropped only for kinds
    this run finished, so `--only` or a stopped run never loses other items."""
    items = {k: v for k, v in old.items.items() if k in work or v.kind not in done_kinds}
    items.update(new)
    return IdLock(items=dict(sorted(items.items())))


def counts(lock: IdLock) -> dict[str, dict[str, int]]:
    out: dict[str, dict[str, int]] = {}
    for item in lock.items.values():
        c = out.setdefault(item.kind, {"resolved": 0, "ambiguous": 0, "unresolved": 0})
        c["unresolved" if item.status == "unresolved" else "ambiguous" if item.ambiguous else "resolved"] += 1
    return dict(sorted(out.items()))


def render(lock: IdLock, work: dict[str, Work], notes: dict[str, Any]) -> str:
    """The generated block of docs/seed_review.md: our query text, ids omitted, no Qloo names."""
    out = [
        BEGIN,
        "",
        "### Counts",
        "",
        "| Kind | Resolved | Ambiguous (resolved, review) | Unresolved |",
        "|---|---|---|---|",
    ]
    for kind, c in counts(lock).items():
        out.append(f"| {kind} | {c['resolved']} | {c['ambiguous']} | {c['unresolved']} |")
    rows = [i for i in lock.items.values() if i.status == "unresolved" or i.ambiguous]
    out += ["", "### To review", ""]
    if rows:
        out += [
            "| Kind | Domain | Our query | Status | Confidence | Reason | Used by |",
            "|---|---|---|---|---|---|---|",
        ]
        for i in sorted(rows, key=lambda x: (x.status != "unresolved", x.kind, x.domain, x.query.lower())):
            who = ", ".join(work[i.key].personas) if i.key in work else "-"
            conf = "-" if i.confidence is None else f"{i.confidence:.1f}"
            status = "unresolved" if i.status == "unresolved" else "ambiguous"
            out.append(
                f"| {i.kind} | {i.domain} | {i.query} | {status} | {conf} | {i.reason or '-'} | {who} |"
            )
    else:
        out.append("Nothing to review.")
    if pag := notes.get("pagination"):
        listed = ", ".join(
            f"{t}: {v['count']}" + (f" (page 2: {v['page2']})" if v.get("page2") else "")
            for t, v in sorted(pag.items())
        )
        full = any(v.get("page2") for v in pag.values())
        out += [
            "",
            f"Audience listings (take={AUDIENCE_TAKE}): {listed}."
            + ("" if full else " No type filled a page."),
        ]
    out += ["", END]
    return "\n".join(out)


def write_review(block: str) -> None:
    text = REVIEW.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END) :]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    REVIEW.write_text(text, encoding="utf-8", newline="\n")


async def run(a: argparse.Namespace, client: QlooClient) -> dict[str, Any]:
    cat = load_catalog(CONFIG)
    work = work_list(cat)
    kinds = [a.only] if a.only else list(KINDS)
    try:
        old = load_lock(CONFIG)
    except ConfigError:
        old = IdLock()
    r = Resolver(client, max_calls=a.max_calls, dry=a.dry_run, previous=old)
    done: set[str] = set()
    stopped = collapse = None
    try:
        for kind in kinds:
            await getattr(r, kind)([w for w in work.values() if w.kind == KINDS[kind]])
            done.add(KINDS[kind])
        if "audience" in done:
            r.check_distinct(cat)
    except Stop as exc:
        stopped = str(exc)
    except Collapse as exc:
        collapse = str(exc)
    out = {
        "plan": dict(r.plan),
        "live_calls": r.used(),
        "stopped": stopped,
        "collapse": collapse,
        "notes": r.notes,
        "failed": r.failures,
    }
    if a.dry_run:
        return out
    detail = json.loads(DETAIL.read_text(encoding="utf-8")) if DETAIL.is_file() else {}
    DETAIL.parent.mkdir(parents=True, exist_ok=True)
    DETAIL.write_text(
        json.dumps({**detail, **r.detail}, sort_keys=True, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    if collapse:
        return out  # never lock a set of ids that makes two personas' answer keys identical
    lock = merge(old, r.items, work, done)
    write_lock(lock, CONFIG / LOCK_FILE)
    write_review(render(lock, work, r.notes))
    out["counts"] = counts(lock)
    return out


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", choices=list(KINDS), help="resolve one kind only")
    p.add_argument(
        "--dry-run", action="store_true", help="list planned lookups; make no calls, write nothing"
    )
    p.add_argument("--max-calls", type=int, default=150, help="hard stop on live calls for this run")
    return p


def main(argv: list[str] | None = None) -> int:
    a = parser().parse_args(argv)
    client = QlooClient(Settings(qloo_mode="replay")) if a.dry_run else make_client("live")
    try:
        out = asyncio.run(run(a, client))
    finally:
        client.db.close()
    label = "would be live" if a.dry_run else "live calls"
    for kind, n in sorted(out["plan"].items()):
        print(f"{kind}: {n} {label}")
    print(f"total: {sum(out['plan'].values())} {label}")
    if out.get("failed") and not a.dry_run:  # in a dry run, uncached lookups are expected misses
        print(
            f"WARNING: {out['failed']} lookups failed; their previous lock entries were kept where they existed"
        )
    for kind, c in (out.get("counts") or {}).items():
        print(f"{kind}: {c['resolved']} resolved, {c['ambiguous']} ambiguous, {c['unresolved']} unresolved")
    if out["collapse"]:
        print(f"STOPPED, lock not written: {out['collapse']}")
        return 2
    if out["stopped"]:
        print(out["stopped"])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
