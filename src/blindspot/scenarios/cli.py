"""`blindspot scenarios build|list|show` (#16). Offline: reads config/ and the id lock only.

    blindspot scenarios build [--out data/scenarios/scenarios.json] [--seed N] [--docs]
    blindspot scenarios list [--probe P] [--city C] [--domain D] [--tag T]
    blindspot scenarios show <scenario id>

`build` writes the scenario file (gitignored: it's regenerated from committed config and lock),
prints the distribution table and the output hash, and with `--docs` also rewrites the generated
table in docs/scenarios.md. Two builds from the same config and lock print the same hash.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

from ..catalog import load_catalog
from ..idlock import load_lock
from .generator import DEFAULT_SEED, ScenarioSet, generate
from .models import Scenario

DEFAULT_OUT = Path("data/scenarios/scenarios.json")
DOC = Path("docs/scenarios.md")
BEGIN = "<!-- BEGIN scenario distribution: generated by `blindspot scenarios build --docs` -->"
END = "<!-- END scenario distribution -->"


def distribution(ss: ScenarioSet) -> str:
    """Markdown tables: counts by probe x city and probe x domain, then the subsets."""
    sc = ss.scenarios
    probes = list(dict.fromkeys(s.probe_type for s in sc))

    def table(attr: str, title: str) -> list[str]:
        cols = sorted({getattr(s, attr) for s in sc})
        n = Counter((s.probe_type, getattr(s, attr)) for s in sc)
        out = [f"| {title} | " + " | ".join(cols) + " | Total |", "|---|" + "---|" * (len(cols) + 1)]
        for p in probes:
            row = [n[(p, c)] for c in cols]
            out.append(f"| {p} | " + " | ".join(map(str, row)) + f" | {sum(row)} |")
        totals = [sum(n[(p, c)] for p in probes) for c in cols]
        out.append("| **Total** | " + " | ".join(map(str, totals)) + f" | **{len(sc)}** |")
        return out

    tags = Counter(t for s in sc for t in s.tags)
    pairs = {s.pair_id for s in sc if s.pair_id and s.probe_type == "swap" and "demo" in s.tags}
    hold = Counter(s.probe_type for s in sc if "holdout" in s.tags)
    lines = [
        f"{len(sc)} scenarios from seed {ss.seed} (inputs `{ss.inputs_hash}`).",
        "",
        *table("city_id", "Probe \\ city"),
        "",
        *table("domain_id", "Probe \\ domain"),
        "",
        "| Subset | Scenarios | Notes |",
        "|---|---|---|",
        f"| demo | {tags['demo']} | {len(pairs)} swap pairs |",
        f"| extended | {tags['extended']} | |",
        f"| holdout | {tags['holdout']} | " + ", ".join(f"{p} {hold[p]}" for p in probes) + " |",
    ]
    if ss.skipped:
        lines += ["", "Skipped:", *[f"- {x}" for x in ss.skipped]]
    return "\n".join(lines)


def write_docs(text: str, doc: Path | None = None) -> None:
    doc = doc or DOC  # looked up at call time
    body = doc.read_text(encoding="utf-8")
    block = f"{BEGIN}\n\n{text}\n\n{END}"
    if BEGIN in body:
        body = body[: body.index(BEGIN)] + block + body[body.index(END) + len(END) :]
    else:
        body = body.rstrip("\n") + "\n\n## Scenario distribution\n\n" + block + "\n"
    doc.write_text(body, encoding="utf-8", newline="\n")


def load_set(path: Path) -> list[Scenario]:
    if not path.is_file():
        raise SystemExit(f"{path} not found; run `blindspot scenarios build` first")
    data = json.loads(path.read_text(encoding="utf-8"))
    return [Scenario.model_validate(s) for s in data["scenarios"]]


def _out(text: str) -> None:
    sys.stdout.buffer.write((text + "\n").encode("utf-8"))  # UTF-8 on any console (AGENTS §6)
    sys.stdout.flush()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="blindspot scenarios", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="generate the scenario file")
    b.add_argument("--out", type=Path, default=DEFAULT_OUT)
    b.add_argument("--config", type=Path, default=Path("config"))
    b.add_argument("--seed", type=int, default=DEFAULT_SEED)
    b.add_argument("--docs", action="store_true", help="also rewrite the table in docs/scenarios.md")
    ls = sub.add_parser("list", help="list scenarios")
    ls.add_argument("--file", type=Path, default=DEFAULT_OUT)
    for f in ("probe", "city", "domain", "tag"):
        ls.add_argument(f"--{f}")
    sh = sub.add_parser("show", help="one scenario as JSON")
    sh.add_argument("id")
    sh.add_argument("--file", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args(argv)

    if a.cmd == "build":
        ss = generate(load_catalog(a.config), load_lock(a.config), seed=a.seed)
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(ss.to_json(), encoding="utf-8", newline="\n")
        table = distribution(ss)
        if a.docs:
            write_docs(table)
        _out(table)
        _out(f"\nwrote {a.out}  sha256 {ss.output_hash()}")
        return 0
    scenarios = load_set(a.file)
    if a.cmd == "list":
        keep = [
            s
            for s in scenarios
            if (not a.probe or s.probe_type == a.probe)
            and (not a.city or s.city_id == a.city)
            and (not a.domain or s.domain_id == a.domain)
            and (not a.tag or a.tag in s.tags)
        ]
        for s in keep:
            cols = f"{s.probe_type:<9} {s.domain_id:<8} {s.city_id:<10} {s.persona_id:<20}"
            _out(f"{s.id}  {cols} {','.join(s.tags)}")
        _out(f"{len(keep)} of {len(scenarios)}")
        return 0
    match = [s for s in scenarios if s.id == a.id]
    if not match:
        _out(f"no scenario {a.id!r}")
        return 1
    _out(json.dumps(match[0].model_dump(mode="json"), indent=2, ensure_ascii=False))
    return 0
